const fs = require('node:fs');
const assert = require('node:assert/strict');
const { JSDOM } = require('jsdom');
const html = fs.readFileSync(require('node:path').join(__dirname, '../index.html'), 'utf8');
const key = 'starter-dictation-v2';
const windows = [];
function load(seed) {
  const dom = new JSDOM(html, { url: 'https://feature-adaptive-daily-plan.starter-daily-dictation.pages.dev', runScripts: 'dangerously', beforeParse(w) {
    w.prompt = () => 'reset';
    if (seed) w.localStorage.setItem(key, JSON.stringify(seed));
  }});
  windows.push(dom.window);
  return dom.window;
}
const state = w => JSON.parse(w.localStorage.getItem(key));
const click = (w, id) => w.document.querySelector(id).click();
const today = w => Object.keys(state(w).days).sort().at(-1);
const plan = w => state(w).days[today(w)];
const input = (w, value) => { w.document.querySelector('#newCount').value = String(value); w.document.querySelector('#newCount').dispatchEvent(new w.Event('input')); };
try {
  const w = load();
  click(w, '[data-tab="progress"]');
  assert.equal(w.document.querySelector('#reviewCount'), null);
  input(w, 5);click(w, '#saveSettings');
  assert.match(w.document.querySelector('#proposalText').textContent, /15/);
  click(w, '#reducePlan');
  assert.match(w.document.querySelector('#proposalText').textContent, /3.*10/);
  assert.equal(state(w).settings.newCount, 5, 'reduction is only a draft');
  click(w, '#cancelPlan');
  assert.equal(state(w).settings.newCount, 5);
  click(w, '#saveSettings');click(w, '#reducePlan');click(w, '#confirmPlan');
  assert.equal(state(w).settings.newCount, 3);
  assert.equal(plan(w).newIds.length, 3);
  click(w, '#confirmPlan');assert.equal(state(w).settings.newCount, 3, 'double confirm is harmless');
  for (const bad of ['', 0, -1, 1.5, 21]) {
    input(w, bad);click(w, '#saveSettings');click(w, '#confirmPlan');
    assert.equal(state(w).settings.newCount, 3, 'invalid input must not save');
    assert.match(w.document.querySelector('#settingMsg').textContent, /整数/);
  }
  input(w, 5);click(w, '#saveSettings');click(w, '#confirmPlan');
  input(w, 5);click(w, '#saveSettings');input(w, 8);click(w, '#confirmPlan');
  assert.equal(state(w).settings.newCount, 5, 'editing input invalidates the previous proposal');
  input(w, 1);click(w, '#saveSettings');
  assert(w.document.querySelector('#reducePlan').disabled, 'minimum intake is explicit');
  click(w, '#cancelPlan');
  let spoken;
  w.speechSynthesis = { cancel() {}, getVoices: () => [{ lang: 'en-GB' }], speak(u) { spoken=u; } };
  w.SpeechSynthesisUtterance = function(text) { this.text=text; };
  click(w, '[data-tab="today"]');click(w, '[data-say]');
  assert.equal(spoken.lang, 'en-GB');
  click(w, '[data-tab="words"]');assert.equal(w.document.querySelectorAll('.bank-word').length, 495);
  click(w, '[data-bank-say]');assert(spoken.text);
  click(w, '[data-tab="today"]');
  const first = [...plan(w).newIds];
  for (const id of first) click(w, `[data-know="${id}"]`);
  click(w, '[data-test-days="1"]');
  assert.deepEqual([...plan(w).reviewIds].sort((a,b)=>a-b), [...first].sort((a,b)=>a-b), 'all five yesterday words must return');
  const seed = state(w), date = today(w);
  for (let id = 300; id < 307; id++) seed.memory[id] = { stage: 1, learnedAt: '2020-01-01', lastReviewed: '2020-01-02', nextReview: '2020-01-04' };
  seed.settings.reviewCount = 0; // Old preferences must not suppress any due words.
  const crowded = load(seed);
  assert.equal(plan(crowded).reviewIds.length, 10);
  assert.equal(plan(crowded).newIds.length, 5);
  assert(first.every(id => plan(crowded).reviewIds.includes(id)));
  assert(first.includes(plan(crowded).reviewIds[0]), 'yesterday first reviews take priority over backlog');
  const done = plan(crowded).newIds[0];click(crowded, `[data-know="${done}"]`);
  const heavySeed = state(crowded);
  for (let id = 307; id < 315; id++) heavySeed.memory[id] = { stage: 0, learnedAt: '2020-01-01', lastReviewed: '2020-01-01', nextReview: '2020-01-02' };
  const heavy = load(heavySeed);
  assert.equal(plan(heavy).reviewIds.length, 10);
  assert.equal(plan(heavy).newIds.length, 5, 'reviews cannot take new-word slots');
  assert(plan(heavy).newIds.includes(done));
  assert(heavy.document.querySelector('.word-row.done .crossed'));
  assert.match(heavy.document.querySelector('#backlogText').textContent, /明天继续排队/);
  const stable = plan(heavy);
  const reloaded = load(state(heavy));assert.deepEqual(plan(reloaded), stable, 'refresh is idempotent');
  click(heavy, '[data-test-days="2"]');
  assert.equal(plan(heavy).reviewIds.length, 10, 'missed reviews carry forward in bounded batches');
  assert.equal(plan(heavy).newIds.length, 5);
  assert.equal(state(heavy).memory[300].stage, 1, 'missed days never advance memory');
  const notStarted = load({ ...seed, memory: {}, days: { [date]: { date, newIds: [0], reviewIds: [], doneIds: [] } } });
  click(notStarted, '[data-test-days="1"]');assert.equal(plan(notStarted).reviewIds.length, 0, 'displaying a new word does not start its memory clock');
  const fortySeed=JSON.parse(JSON.stringify(seed));
  fortySeed.days={};fortySeed.memory=Object.fromEntries(Array.from({length:40},(_,id)=>[id,{stage:1,learnedAt:'2020-01-01',lastReviewed:'2020-01-02',nextReview:'2020-01-04'}]));
  const forty=load(fortySeed);
  assert.equal(plan(forty).reviewIds.length,10);assert.equal(plan(forty).newIds.length,5);
  assert.match(forty.document.querySelector('#backlogText').textContent,/30/);
  assert.deepEqual(state(forty).memory,fortySeed.memory);
  for(const id of [...plan(forty).reviewIds,...plan(forty).newIds])click(forty,`[data-know="${id}"]`);
  assert.equal(plan(forty).completed,true);assert.equal(plan(forty).reviewIds.length,10);
  const synced=load(state(forty));assert.equal(plan(synced).completed,true);assert.equal(plan(synced).reviewIds.length,10,'reload must not auto-refill');
  click(forty,'#continueReview');assert.equal(plan(forty).reviewIds.length,15);assert.equal(plan(forty).doneIds.length,15);
  assert.equal(plan(forty).extraReview,5);assert.match(forty.document.querySelector('#backlogText').textContent,/25/);
  const extraReload=load(state(forty));assert.equal(plan(extraReload).reviewIds.length,15);
  assert.equal(Object.keys(state(forty).memory).length,45);
  const fifteen=load({...fortySeed,settings:{...fortySeed.settings,newCount:15}});
  assert.equal(plan(fifteen).newIds.length,15);
  assert.equal(plan(fifteen).reviewIds.length,30);
  assert.match(fifteen.document.querySelector('#backlogText').textContent,/10 个/);
  const oldPlan=state(fifteen),oldDay=oldPlan.days[today(fifteen)];
  oldDay.newIds=oldDay.newIds.slice(0,2);
  oldDay.reviewIds=Array.from({length:40},(_,id)=>id);
  oldDay.doneIds=[...oldDay.newIds,...oldDay.reviewIds];
  for(const id of oldDay.newIds)oldPlan.memory[id]={stage:0,learnedAt:oldDay.date,lastReviewed:oldDay.date,nextReview:'2099-01-01'};
  const upgraded=load(oldPlan);
  assert.equal(plan(upgraded).newIds.length,15,'an existing day is topped up from 2 to 15 new words');
  assert.deepEqual(plan(upgraded).reviewIds,oldDay.reviewIds,'the upgrade cannot remove completed reviews to make space');
  assert.equal(plan(upgraded).doneIds.length,42);
  assert.deepEqual(state(upgraded).memory,oldPlan.memory);
  const doneReviews=plan(fifteen).reviewIds.slice(0,28);
  for(const id of doneReviews)click(fifteen,`[data-know="${id}"]`);
  input(fifteen,5);click(fifteen,'#saveSettings');click(fifteen,'#confirmPlan');
  assert.deepEqual(plan(fifteen).reviewIds,doneReviews,'completed reviews are kept even if the target drops below completed work');
  assert.equal(plan(fifteen).newIds.length,5);
  const retry = load();
  const retryId = plan(retry).newIds[0];
  assert.equal(retry.document.querySelector('[data-not-confident]'), null, 'new words should retain the normal completion action');
  click(retry, `[data-know="${retryId}"]`);
  click(retry, '[data-test-days="1"]');
  assert(retry.document.querySelector(`[data-not-confident="${retryId}"]`), 'due reviews should offer the not-confident action');
  const retryDate = today(retry);
  click(retry, `[data-not-confident="${retryId}"]`);
  assert(plan(retry).doneIds.includes(retryId), 'not-confident review should still complete today’s task');
  assert.equal(state(retry).memory[retryId].stage, 0, 'not-confident review should restart at the first review stage');
  const retryTomorrow = new Date(`${retryDate}T12:00:00`);retryTomorrow.setDate(retryTomorrow.getDate()+1);
  const retryDueDate = `${retryTomorrow.getFullYear()}-${String(retryTomorrow.getMonth()+1).padStart(2,'0')}-${String(retryTomorrow.getDate()).padStart(2,'0')}`;
  assert.equal(state(retry).memory[retryId].nextReview, retryDueDate, 'not-confident review should return tomorrow');
  assert.match(retry.document.querySelector('.feedback').textContent, /已安排下一轮复习/);
  click(retry,'[data-tab="words"]');
  assert.equal(retry.document.querySelector('[data-filter="done"]').textContent,'已学习 1');
  assert.equal(retry.document.querySelector('[data-filter="todo"]').textContent,'待学习 494');
  assert.equal(retry.document.querySelector('.bank-review-count').textContent,'复习 1 次','not-confident reviews count even when stage resets');
  click(retry, '[data-test-days="1"]');
  assert(plan(retry).reviewIds.includes(retryId), 'restarted review should reappear in the next round');
  const exhausted = JSON.parse(JSON.stringify(seed));
  exhausted.days = {};
  exhausted.memory = Object.fromEntries(Array.from({length:495}, (_,id) => [id,{stage:6,learnedAt:'2020-01-01',lastReviewed:date,nextReview:'2099-01-01'}]));
  const end = load(exhausted);assert.equal(plan(end).newIds.length, 0, 'exhausted word bank does not recycle learned words as new');
  const reviewHistory=structuredClone(exhausted);
  for(let i=1;i<=8;i++){
    const day=`2020-02-0${i}`;
    reviewHistory.days[day]={date:day,newIds:[],reviewIds:[0],doneIds:[0],completedReviewIds:[0,0]};
  }
  const longReview=load(reviewHistory);click(longReview,'[data-tab="words"]');
  assert.equal(longReview.document.querySelector('.bank-review-count').textContent,'复习 8 次','counts exceed stage cap without double-counting merged history');
  const rollover = load(), stale = rollover.document.querySelector('[data-know]');
  rollover.eval('testDayOffset += 1');stale.click();
  assert.equal(Object.keys(state(rollover).memory).length, 0, 'stale click after midnight refreshes the plan instead of recording an old task');
  assert.equal(Object.keys(state(rollover).days).length, 2);
  click(heavy, '#reset');assert.equal(state(heavy).settings.newCount, 5);assert.equal(Object.keys(state(heavy).memory).length, 0);
  console.log('PASS: recommendation/confirmation, cancellation, validation, next-day recall, not-confident restart, 12/20 overdue reviews, completed preservation, reload, missed days, exhausted bank, reset');
} finally { windows.forEach(w => w.close()); }
